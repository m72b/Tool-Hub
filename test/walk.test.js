const assert=require('assert');const fs=require('fs');const os=require('os');const path=require('path');
const {walkFilesAsync,dirSizeAsync}=require(require('path').join(__dirname,'..','src','core/walk'));
const tmp=fs.mkdtempSync(path.join(os.tmpdir(),'walk-'));
fs.mkdirSync(path.join(tmp,'a/b/c'),{recursive:true});
fs.writeFileSync(path.join(tmp,'root.txt'),'x'.repeat(10));
fs.writeFileSync(path.join(tmp,'a/one.txt'),'y'.repeat(20));
fs.writeFileSync(path.join(tmp,'a/b/two.log'),'z'.repeat(30));
fs.writeFileSync(path.join(tmp,'a/b/c/three.txt'),'w'.repeat(40));
try{fs.symlinkSync(tmp,path.join(tmp,'a/loop'),'dir');}catch(e){}
(async()=>{
let r=await walkFilesAsync(tmp);
assert.strictEqual(r.files.length,4,'recursive count');
assert.strictEqual(r.truncated,false);
r=await walkFilesAsync(tmp,{recursive:false});
assert.strictEqual(r.files.length,1,'non-recursive');
r=await walkFilesAsync(tmp,{maxDepth:1});
assert.strictEqual(r.files.length,2,'depth 1');
r=await walkFilesAsync(tmp,{limit:2});
assert.strictEqual(r.truncated,true,'limit truncates');
assert.strictEqual(r.files.length,2);
r=await walkFilesAsync(tmp,{filter:f=>f.ext==='log'});
assert.strictEqual(r.files.length,1,'filter');
r=await walkFilesAsync(tmp,{followSymlinks:true});
assert.ok(r.files.length<100,'symlink loop did not explode: '+r.files.length);
r=await walkFilesAsync(tmp,{excludeDirs:[path.join(tmp,'a','b')]});
assert.strictEqual(r.files.length,2,'excluded folder skipped');
const controller=new AbortController();controller.abort();
await assert.rejects(()=>walkFilesAsync(tmp,{signal:controller.signal}),e=>e.name==='AbortError','cancel honoured');
const ds=await dirSizeAsync(tmp);
assert.strictEqual(ds.size,100,'dirSize total got '+ds.size);
assert.strictEqual(ds.count,4);
const missing=await walkFilesAsync(path.join(tmp,'nope'));
assert.strictEqual(missing.files.length,0,'missing dir tolerated');
let errs=[];await walkFilesAsync(path.join(tmp,'nope'),{onError:e=>errs.push(e)});
assert.strictEqual(errs.length,1,'onError fired');
fs.rmSync(tmp,{recursive:true,force:true});
console.log('walk.js: all checks passed');
})().catch(err=>{console.error(err);process.exitCode=1;});
